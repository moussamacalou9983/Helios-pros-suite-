/// `INV-EM-NEW-01` — from `I₀ = 0`, every iterate stays in the proved
/// interval, and Newton is the branch taken (eq. 12, P-13).
#[test]
fn inv_em_new_01_newton_stays_within_its_proved_interval() {
    for (name, p) in reference_sets() {
        if p.has_zero_series_resistance() {
            continue; // the closed form applies; covered by INV-EM-RS0-01
        }
        sweep(&p, 25, |v| {
            let out = current_at_voltage(&p, v).expect("inside the quadrant");
            assert_eq!(
                out.method(),
                SolveMethod::Newton,
                "{name} at {} V fell back unexpectedly",
                v.volts()
            );
            let i = out.current().amperes();
            assert!(
                i >= 0.0 && i <= p.photocurrent().amperes() + p.saturation_current().amperes(),
                "{name}: iterate {i} outside the invariant"
            );
        });
    }
}

