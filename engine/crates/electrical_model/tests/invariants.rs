//! The 35 software invariants, one per proved property.
//!
//! Each test names the property of
//! `docs/design/36-statut-epistemique-electrical-model.md` §3 it enforces
//! and the equation of doc 35 that proves it. The naming is the
//! traceability: `inv_em_sol_01` enforces `INV-EM-SOL-01`, which
//! translates `P-08`, proved in doc 35 §3.2.
//!
//! **These tests do not prove anything.** They check that the code
//! implements what the proofs establish. A failure means the code or the
//! proof is wrong — never that the property is false.

