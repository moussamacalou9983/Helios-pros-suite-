/// `INV-EM-SOL-01` and `INV-EM-SOL-02` — the root exists and is unique
/// (P-08, P-09).
///
/// Uniqueness is checked as agreement between two independent methods:
/// Newton, and the bracketed fallback. Two methods converging to the same
/// point is the strongest check available without an external oracle.
#[test]
fn inv_em_sol_01_02_the_root_exists_and_is_unique() {
    for (name, p) in reference_sets() {
        sweep(&p, 25, |v| {
            let by_newton = current_at_voltage(&p, v)
                .unwrap_or_else(|e| panic!("{name} at {} V: {e}", v.volts()));
            let by_bracket = current_at_voltage_by_bracketing(&p, v)
                .unwrap_or_else(|e| panic!("{name} at {} V: {e}", v.volts()));
            let gap = (by_newton.current().amperes() - by_bracket.current().amperes()).abs();
            let allowance = by_newton.error_bound(&p) + by_bracket.error_bound(&p);
            assert!(
                gap <= allowance,
                "{name} at {} V: gap {gap:e} exceeds {allowance:e}",
                v.volts()
            );
        });
    }
}

/// `INV-EM-SOL-03` — the root lies in `[0, I_ph + I_0]` (eq. 9, P-10).
#[test]
fn inv_em_sol_03_the_root_lies_within_the_proved_bracket() {
    for (name, p) in reference_sets() {
        let upper = p.photocurrent().amperes() + p.saturation_current().amperes();
        sweep(&p, 25, |v| {
            let i = solve(&p, v);
            assert!(i >= 0.0, "{name} at {} V: I = {i}", v.volts());
            assert!(
                i <= upper,
                "{name} at {} V: I = {i} above {upper}",
                v.volts()
            );
        });
    }
}

/// `INV-EM-SOL-04` — `I(V)` is strictly decreasing (eq. 10, P-11).
#[test]
fn inv_em_sol_04_the_characteristic_is_strictly_decreasing() {
    for (name, p) in reference_sets() {
        let v_oc = open_circuit_voltage(&p).volts();
        let mut previous = f64::INFINITY;
        for k in 0..=60 {
            let v = Voltage::from_volts(v_oc * (f64::from(k) / 60.0));
            let i = solve(&p, v);
            assert!(
                i < previous,
                "{name}: I did not decrease at {} V",
                v.volts()
            );
            previous = i;
            // The analytic slope agrees on the sign.
            let slope = current_voltage_slope(Current::from_amperes(i), v, &p)
                .expect("both derivatives are finite in the quadrant");
            assert!(slope < 0.0, "{name}: dI/dV = {slope}");
        }
    }
}

