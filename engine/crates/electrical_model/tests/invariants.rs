/// `INV-EM-OVF-03` — no dangerous underflow (P-22).
///
/// As `u → −∞` the diode term tends to `−I_0`, finite and correct; the
/// loss occurs on a term already negligible against `I_ph`.
#[test]
fn inv_em_ovf_03_underflow_is_harmless() {
    let p = nominal();
    // Deep reverse of the exponent: the diode term must tend to -I_0.
    for u in [-100.0, -700.0, -1e4] {
        let term = electrical_model::single_diode::diode_term(u, &p);
        assert!(term.is_finite(), "u = {u}: term = {term}");
        assert!(
            (term + p.saturation_current().amperes()).abs() <= p.saturation_current().amperes(),
            "u = {u}: term = {term} should approach -I_0"
        );
    }
}

// =====================================================================
// INV-EM-RS0 — the zero-series branch
// =====================================================================

/// `INV-EM-RS0-01` — `R_s = 0` is exact and takes no iteration
/// (eq. 18, P-23).
///
/// Compared against an **independent** evaluation of equation (18),
/// written out directly and using none of the solver's machinery.
#[test]
fn inv_em_rs0_01_the_zero_series_branch_is_exact() {
    let p = set(10.4, 2.5e-10, 0.0, 800.0, 1.85);
    let v_oc = open_circuit_voltage(&p).volts();
    for k in 0..=40 {
        let v = v_oc * (f64::from(k) / 40.0);
        let out = current_at_voltage(&p, Voltage::from_volts(v)).unwrap();
        assert_eq!(out.method(), SolveMethod::ClosedFormZeroSeries);
        assert_eq!(out.iterations(), 0, "the closed form must not iterate");

        let independent = 10.4 - 2.5e-10 * ((v / 1.85_f64).exp() - 1.0) - v / 800.0;
        let got = out.current().amperes();
        // The tolerance is absolute at the scale of the photocurrent, not
        // relative to the result, and that distinction is physical rather
        // than cosmetic. Equation (18) sums three terms each of magnitude
        // up to `I_ph`; approaching `V_oc` they cancel, and the result
        // falls to ~1e-14 A while the summands stay at ~10 A. No
        // evaluation order can recover accuracy relative to a difference
        // that small — the achievable error is a few ULP of the *terms*.
        // Demanding relative accuracy on the result would be demanding
        // that f64 subtraction be exact, which is not a property the code
        // could be fixed to have. This is the same scaling policy as
        // `RELATIVE_RESIDUAL_TOLERANCE`, and for the same reason.
        let scale = 8.0 * f64::EPSILON * p.photocurrent().amperes();
        assert!(
            (got - independent).abs() <= scale,
            "V = {v}: got {got}, equation (18) gives {independent}, \
             gap exceeds {scale:e}"
        );
    }
}

/// `INV-EM-RS0-02` — no threshold is used for `R_s → 0` (P-24).
///
/// The general branch contains no division by `R_s`, so a vanishing but
/// non-zero `R_s` goes through it without difficulty and agrees with the
/// closed form.
#[test]
fn inv_em_rs0_02_no_threshold_is_used_near_zero_series() {
    let exact = set(10.4, 2.5e-10, 0.0, 800.0, 1.85);
    let v = Voltage::from_volts(30.0);
    let reference = solve(&exact, v);

    for r_s in [1e-300, 1e-30, 1e-12, 1e-9, 1e-6] {
        let p = set(10.4, 2.5e-10, r_s, 800.0, 1.85);
        // Exact predicate: a tiny positive resistance is not zero.
        assert!(
            !p.has_zero_series_resistance(),
            "R_s = {r_s} must not be treated as zero"
        );
        let out = current_at_voltage(&p, v).unwrap();
        assert_eq!(
            out.method(),
            SolveMethod::Newton,
            "R_s = {r_s} must take the general branch"
        );
        assert!(
            (out.current().amperes() - reference).abs() < 1e-6,
            "R_s = {r_s}: {} vs {reference}",
            out.current().amperes()
        );
    }
}

// =====================================================================
// INV-EM-MPP — the junction-voltage primitives
//
// The maximum-power-point search itself is NOT implemented in this
// sub-phase. These invariants cover the primitives its proof rests on,
// which are part of the kernel.
// =====================================================================

/// `INV-EM-MPP-01` — `φ' < 0` and `φ'' < 0` (eq. 22, 23, P-25).
#[test]
fn inv_em_mpp_01_the_junction_derivatives_are_negative() {
    for (name, p) in reference_sets() {
        let v_oc = open_circuit_voltage(&p).volts();
        for k in 0..=30 {
            let v_j = Voltage::from_volts(v_oc * f64::from(k) / 30.0);
            assert!(
                junction_current_slope(v_j, &p) < 0.0,
                "{name}: phi' at {}",
                v_j.volts()
            );
            assert!(
                junction_current_curvature(v_j, &p) < 0.0,
                "{name}: phi'' at {}",
                v_j.volts()
            );
        }
    }
}

/// `INV-EM-MPP-02` — `V ↔ V_j` is an increasing bijection (eq. 24, P-26).
///
/// `dV/dV_j = 1 + R_s|φ'| > 0`, so the map is strictly increasing.
#[test]
fn inv_em_mpp_02_the_junction_map_is_strictly_increasing() {
    for (name, p) in reference_sets() {
        let v_oc = open_circuit_voltage(&p).volts();
        let mut previous = f64::NEG_INFINITY;
        for k in 0..=40 {
            let v_j = v_oc * f64::from(k) / 40.0;
            let derivative = 1.0
                - p.series_resistance().ohms()
                    * junction_current_slope(Voltage::from_volts(v_j), &p);
            assert!(derivative > 0.0, "{name}: dV/dV_j = {derivative}");
            let v = v_j
                - p.series_resistance().ohms()
                    * current_at_junction_voltage(Voltage::from_volts(v_j), &p);
            assert!(v > previous, "{name}: V did not increase with V_j");
            previous = v;
        }
    }
}

/// `INV-EM-MPP-10` — `φ` is explicit: it reproduces the residual without
/// any solve (eq. 21, P-34).
///
/// `f(I; V) = φ(V + I·R_s) − I` identically. This is what decouples the
/// maximum-power-point search from the implicit solver.
#[test]
fn inv_em_mpp_10_the_junction_form_is_explicit_and_exact() {
    for (name, p) in reference_sets() {
        sweep(&p, 20, |v| {
            for j in 0..=10 {
                let i = p.photocurrent().amperes() * f64::from(j) / 10.0;
                let v_j = junction_voltage(v, Current::from_amperes(i), p.series_resistance());
                let phi = current_at_junction_voltage(v_j, &p);
                let f = residual(Current::from_amperes(i), v, &p);
                assert!(
                    (f - (phi - i)).abs() <= 1e-9 * p.photocurrent().amperes().max(1.0),
                    "{name}: f = {f}, phi - I = {}",
                    phi - i
                );
            }
        });
    }
}

