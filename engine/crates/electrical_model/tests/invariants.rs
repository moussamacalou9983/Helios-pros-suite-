/// `INV-EM-ERR-01` — the residual bounds the error (eq. 14, P-15).
///
/// Checked against an independent reference: a high-precision bracketed
/// solve driven to the bracket's own width.
#[test]
fn inv_em_err_01_the_residual_bounds_the_error() {
    for (name, p) in reference_sets() {
        sweep(&p, 20, |v| {
            let out = current_at_voltage(&p, v).expect("inside the quadrant");
            let reference = current_at_voltage_by_bracketing(&p, v).expect("inside the quadrant");
            let error = (out.current().amperes() - reference.current().amperes()).abs();
            let bound = out.error_bound(&p) + reference.error_bound(&p);
            assert!(
                error <= bound,
                "{name}: error {error:e} exceeds bound {bound:e}"
            );
            // And the bound is the residual, not an estimate.
            assert!(out.error_bound(&p) >= out.residual().abs());
        });
    }
}

/// `INV-EM-ERR-02` — the current bound does **not** transpose to voltage
/// (P-17).
///
/// `∂f/∂I` is dimensionless and bounded below by 1; `∂f/∂V` is a
/// conductance whose magnitude can be far below 1. A test that assumed the
/// same bound in voltage would be dimensionally wrong.
#[test]
fn inv_em_err_02_the_voltage_bound_has_a_different_form() {
    let p = nominal();
    let i = Current::from_amperes(5.0);
    let v = Voltage::from_volts(30.0);

    let d_i = residual_derivative(i, v, &p).abs();
    let d_v = residual_voltage_derivative(i, v, &p).abs();

    assert!(d_i >= 1.0, "|df/dI| = {d_i} must be at least 1");
    // With R_sh = 800 ohm the conductance is of order 1e-3: transposing
    // the current bound would understate the voltage error by that factor.
    assert!(
        d_v < 1.0,
        "|df/dV| = {d_v} is a conductance, not bounded by 1"
    );
    // The voltage error bound is |h| * R_sh, which is far larger.
    assert!(1.0 / d_v > 100.0);
}

