/// `INV-EM-DOM-01`, `INV-EM-DOM-02`, `INV-EM-DOM-03`, `INV-EM-DOM-04` and
/// `INV-EM-DOM-05` — each hypothesis of `𝓗` is refused by name.
///
/// The five identifiers are spelled out rather than written as a range so
/// that the traceability matrix can be regenerated by searching the
/// sources: a range would leave four of them findable in the
/// specification and in no test.
#[test]
fn inv_em_dom_01_to_05_each_hypothesis_is_refused_by_name() {
    let cases: [(ParameterFault, f64, f64, f64, f64, f64); 5] = [
        (ParameterFault::Photocurrent, 0.0, 2.5e-10, 0.3, 800.0, 1.85),
        (
            ParameterFault::SaturationCurrent,
            10.4,
            0.0,
            0.3,
            800.0,
            1.85,
        ),
        (
            ParameterFault::SeriesResistance,
            10.4,
            2.5e-10,
            -0.3,
            800.0,
            1.85,
        ),
        (
            ParameterFault::ShuntResistance,
            10.4,
            2.5e-10,
            0.3,
            0.0,
            1.85,
        ),
        (
            ParameterFault::ModifiedIdealityFactor,
            10.4,
            2.5e-10,
            0.3,
            800.0,
            -1.0,
        ),
    ];
    for (expected, i_ph, i_0, r_s, r_sh, a) in cases {
        let outcome = SingleDiodeParameters::new(
            Current::from_amperes(i_ph),
            Current::from_amperes(i_0),
            Resistance::from_ohms(r_s),
            Resistance::from_ohms(r_sh),
            ModifiedIdealityFactor::from_volts(a),
        );
        match outcome {
            Err(ElectricalModelError::InvalidParameters { fault, value }) => {
                assert_eq!(fault, expected);
                assert!(fault.hypothesis().contains(fault.parameter()));
                assert_eq!(value, [i_ph, i_0, r_s, r_sh, a][expected_index(expected)]);
            }
            other => panic!("{expected:?} must be refused, got {other:?}"),
        }
    }
}

fn expected_index(f: ParameterFault) -> usize {
    match f {
        ParameterFault::Photocurrent => 0,
        ParameterFault::SaturationCurrent => 1,
        ParameterFault::SeriesResistance => 2,
        ParameterFault::ShuntResistance => 3,
        _ => 4,
    }
}

/// `INV-EM-DOM-06` and `INV-EM-DOM-07` — the cell count and the cell
/// temperature are refused by name (H-6, H-7).
///
/// These two hypotheses do not live on [`SingleDiodeParameters`]: `N_s`
/// and `T_c` enter through equation (2), which builds `a`. Checking them
/// only at the constructor would report the wrong parameter — the caller
/// would be told `a ≤ 0` when what they got wrong was the cell count or
/// the temperature unit.
#[test]
fn inv_em_dom_06_07_the_cell_count_and_temperature_are_refused_by_name() {
    let good = Temperature::from_celsius(25.0);

    // H-6: a module has at least one cell.
    match ModifiedIdealityFactor::from_diode(1.0, 0, good) {
        Err(ElectricalModelError::InvalidParameters { fault, value }) => {
            assert_eq!(fault, ParameterFault::CellsInSeries);
            assert_eq!(value, 0.0);
            assert!(fault.hypothesis().contains("N_s"));
        }
        other => panic!("N_s = 0 must be refused, got {other:?}"),
    }

    // H-7: a non-positive absolute temperature is a unit error, most
    // often celsius passed where kelvin was expected.
    for kelvin in [0.0, -1.0, f64::NAN] {
        match ModifiedIdealityFactor::from_diode(1.0, 72, Temperature::from_kelvin(kelvin)) {
            Err(ElectricalModelError::InvalidParameters { fault, .. }) => {
                assert_eq!(fault, ParameterFault::CellTemperature);
                assert!(fault.hypothesis().contains("T_c"));
            }
            other => panic!("T_c = {kelvin} K must be refused, got {other:?}"),
        }
    }

    // And the ideality factor itself, which is neither H-6 nor H-7 but
    // would otherwise produce `a = 0` and be reported against `a`.
    for n in [0.0, -1.0, f64::INFINITY] {
        match ModifiedIdealityFactor::from_diode(n, 72, good) {
            Err(ElectricalModelError::InvalidParameters { fault, .. }) => {
                assert_eq!(fault, ParameterFault::DiodeIdealityFactor);
            }
            other => panic!("n = {n} must be refused, got {other:?}"),
        }
    }

    assert!(ModifiedIdealityFactor::from_diode(1.0, 1, good).is_ok());
}

/// `INV-EM-DOM-08` — the operating quadrant is enforced exactly.
///
/// `V ≤ V_oc` **is** `f(0; V) ≥ 0`, by the strict decrease of `f(0; ·)`
/// in `V` (eq. 8). The test compares the solver's refusal boundary with an
/// independent bisection on the residual alone.
#[test]
fn inv_em_dom_08_the_operating_quadrant_is_enforced_exactly() {
    for (name, p) in reference_sets() {
        let v_oc = open_circuit_voltage(&p).volts();
        // Just inside: accepted.
        let inside = Voltage::from_volts(v_oc * (1.0 - 1e-9));
        assert!(
            current_at_voltage(&p, inside).is_ok(),
            "{name}: V just below V_oc must be admissible"
        );
        // Well outside: refused.
        for factor in [1.001, 1.5, 2.0] {
            let outside = Voltage::from_volts(v_oc * factor);
            assert!(
                matches!(
                    current_at_voltage(&p, outside),
                    Err(ElectricalModelError::OutOfDomain { .. })
                ),
                "{name}: V = {} V must be refused",
                outside.volts()
            );
        }
        // Negative and non-finite are refused.
        for bad in [-1.0, f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
            assert!(matches!(
                current_at_voltage(&p, Voltage::from_volts(bad)),
                Err(ElectricalModelError::OutOfDomain { .. })
            ));
        }
    }
}

/// `INV-EM-DOM-09` — the overflow guard refuses before computing.
#[test]
fn inv_em_dom_09_the_overflow_guard_refuses_before_computing() {
    // The dominant term is I_ph*R_s/a, not V_oc/a.
    for (r_s, a) in [(200.0, 1.85), (0.30, 0.001), (50.0, 0.5)] {
        let outcome = SingleDiodeParameters::new(
            Current::from_amperes(10.4),
            Current::from_amperes(2.5e-10),
            Resistance::from_ohms(r_s),
            Resistance::from_ohms(800.0),
            ModifiedIdealityFactor::from_volts(a),
        );
        match outcome {
            Err(ElectricalModelError::NumericalOverflow { guard, limit }) => {
                assert!(guard > limit);
                assert_eq!(limit, LN_F64_MAX);
            }
            other => panic!("R_s = {r_s}, a = {a} must be refused, got {other:?}"),
        }
    }
}

