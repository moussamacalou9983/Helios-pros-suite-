/// `INV-EM-FBK-04` — the cross-check entry point enforces the same
/// quadrant as the production one.
///
/// [`current_at_voltage_by_bracketing`] exists so that Newton can be
/// checked against something that owes it nothing. That only works if the
/// two agree on which voltages are admissible: a cross-check that accepted
/// inputs the production path refuses would be comparing two different
/// problems.
#[test]
fn inv_em_fbk_04_the_cross_check_enforces_the_same_quadrant() {
    for (name, p) in reference_sets() {
        let v_oc = open_circuit_voltage(&p).volts();
        for bad in [
            -1.0,
            f64::NAN,
            f64::INFINITY,
            f64::NEG_INFINITY,
            v_oc * 1.001,
            v_oc * 2.0,
        ] {
            let v = Voltage::from_volts(bad);
            assert!(
                matches!(
                    current_at_voltage_by_bracketing(&p, v),
                    Err(ElectricalModelError::OutOfDomain { .. })
                ),
                "{name}: bracketing accepted V = {bad}"
            );
            // And the two entry points refuse the same inputs, which is
            // the property that makes the cross-check meaningful.
            assert!(
                matches!(
                    current_at_voltage(&p, v),
                    Err(ElectricalModelError::OutOfDomain { .. })
                ),
                "{name}: the two entry points disagree at V = {bad}"
            );
        }
    }
}

/// `INV-EM-FBK-03` — the bound is independent of module size (P-20).
///
/// Both the bracket width and the tolerance scale with the photocurrent,
/// so their ratio — and hence the number of halvings — does not.
#[test]
fn inv_em_fbk_03_the_bound_is_independent_of_module_size() {
    let mut bounds = Vec::new();
    for i_ph in [1e-3, 1e-1, 1.0, 10.4, 30.0] {
        let p = set(i_ph, 2.5e-10, 0.30, 800.0, 1.85);
        bounds.push(fallback_iteration_bound(&p));
    }
    let first = bounds[0];
    for b in &bounds {
        assert_eq!(*b, first, "the bound varied with module size: {bounds:?}");
    }
}

