/// `INV-EM-DIM-01` — equation (1) is homogeneous in amperes, and the
/// **type system** is what enforces it (P-02).
///
/// The proof of P-02 is that every term of the residual is a current. A
/// runtime test cannot check that: by the time a value is an `f64` its
/// dimension is gone. What can be checked is that the code has no way to
/// write an inhomogeneous expression, and that is a compile-time property.
///
/// The compile-time half of this invariant lives in the library's own
/// documentation — `electrical_model::single_diode`, section "Dimensional
/// homogeneity is a compile-time property" — because `compile_fail` blocks
/// are only executed by rustdoc on a library target, never on an
/// integration test. Placed here they would have been decoration.
///
/// The runtime half is what remains checkable from outside: `Ω · A` yields
/// a `Voltage`, in both multiplication orders.
#[test]
fn inv_em_dim_01_the_equation_is_homogeneous_by_construction() {
    let drop: Voltage = Resistance::from_ohms(0.30) * Current::from_amperes(10.0);
    assert!((drop.volts() - 3.0).abs() < 1e-15);
    let commuted: Voltage = Current::from_amperes(10.0) * Resistance::from_ohms(0.30);
    assert_eq!(drop.volts(), commuted.volts());

    // And the junction voltage, which is `V + I·R_s`, is a voltage.
    let v_j = junction_voltage(
        Voltage::from_volts(30.0),
        Current::from_amperes(10.0),
        Resistance::from_ohms(0.30),
    );
    assert!((v_j.volts() - 33.0).abs() < 1e-13);
}

/// `INV-EM-DIM-02` — the exponent is dimensionless.
///
/// It is `V/V`, which is why the whole equation is homogeneous in amperes
/// (eq. 1, §1.4). Checked by scaling: multiplying `V`, `I·R_s` and `a` by
/// a common factor must leave `u` unchanged.
#[test]
fn inv_em_dim_02_the_exponent_is_dimensionless() {
    let p = set(10.4, 2.5e-10, 0.30, 800.0, 1.85);
    let scaled = set(10.4, 2.5e-10, 0.30 * 3.0, 800.0, 1.85 * 3.0);
    let u = exponent(Voltage::from_volts(30.0), Current::from_amperes(5.0), &p);
    let u_scaled = exponent(
        Voltage::from_volts(90.0),
        Current::from_amperes(5.0),
        &scaled,
    );
    assert!((u - u_scaled).abs() < 1e-12, "u = {u}, scaled = {u_scaled}");
}

/// `INV-EM-DIM-03` — `∂f/∂I` is dimensionless, `INV-EM-DIM-04` — `∂f/∂V`
/// is a conductance.
///
/// The contrast is what makes the error bound hold in current and fail to
/// transpose to voltage (§5.4). Checked by their magnitudes: `|∂f/∂I| ≥ 1`
/// always, while `∂f/∂V` scales like `1/R_sh`.
#[test]
fn inv_em_dim_03_04_the_two_derivatives_have_different_dimensions() {
    let p = nominal();
    let i = Current::from_amperes(5.0);
    let v = Voltage::from_volts(30.0);

    // Dimensionless: bounded below by 1 regardless of the resistances.
    assert!(residual_derivative(i, v, &p).abs() >= 1.0);

    // A conductance: doubling R_sh roughly halves the shunt contribution.
    let wide = set(10.4, 2.5e-10, 0.30, 1.6e3, 1.85);
    let narrow = set(10.4, 2.5e-10, 0.30, 8.0e2, 1.85);
    let d_wide = residual_voltage_derivative(i, v, &wide);
    let d_narrow = residual_voltage_derivative(i, v, &narrow);
    assert!(d_narrow < d_wide, "the narrower shunt must conduct more");
}

/// `INV-EM-DIM-05` — the error bound of equation (14) is dimensionally
/// coherent (P-16).
///
/// `|I − I*| ≤ |f(I)|` compares a current with a residual, and that is
/// only legitimate because the residual **is** a current: equation (3) is
/// homogeneous in amperes, and `∂f/∂I` is dimensionless, so dividing by it
/// would not change units either. The corresponding statement in voltage
/// is *not* of this form (`INV-EM-ERR-02`), and the contrast is the whole
/// content of P-16.
///
/// Checked by scaling: multiplying every current in the problem by a
/// factor must multiply both sides of the inequality by the same factor.
/// A bound that was secretly a voltage, or dimensionless, would not scale
/// with the currents.
#[test]
fn inv_em_dim_05_the_error_bound_scales_as_a_current() {
    let v = Voltage::from_volts(20.0);
    let factor = 7.0;

    // Scaling `I_ph`, `I_0` and `1/R_sh` by the same factor scales the
    // whole residual by it, at fixed voltage: every term of equation (3)
    // is proportional to a current.
    let base = set(10.4, 2.5e-10, 0.0, 800.0, 1.85);
    let scaled = set(10.4 * factor, 2.5e-10 * factor, 0.0, 800.0 / factor, 1.85);

    let i = Current::from_amperes(4.0);
    let f_base = residual(i, v, &base);
    let f_scaled = residual(Current::from_amperes(4.0 * factor), v, &scaled);
    assert!(
        (f_scaled - factor * f_base).abs() <= 1e-12 * (factor * f_base).abs(),
        "f scaled to {f_scaled}, expected {}",
        factor * f_base
    );

    // And the bound reported by the solver scales the same way, because
    // it is that residual plus a rounding term proportional to `I_ph`.
    let out_base = current_at_voltage(&base, v).expect("inside the quadrant");
    let out_scaled = current_at_voltage(&scaled, v).expect("inside the quadrant");
    let ratio = out_scaled.error_bound(&scaled) / out_base.error_bound(&base);
    assert!(
        (ratio - factor).abs() < 1e-9,
        "the bound scaled by {ratio}, not by {factor}"
    );

    // `∂f/∂I` is dimensionless, so it does not scale at all.
    let d_base = residual_derivative(i, v, &base);
    let d_scaled = residual_derivative(Current::from_amperes(4.0 * factor), v, &scaled);
    assert!(
        (d_scaled - d_base).abs() < 1e-9,
        "df/dI moved from {d_base} to {d_scaled} under a pure current scaling"
    );
}

