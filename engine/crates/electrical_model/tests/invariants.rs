// =====================================================================

/// `INV-EM-TOL-01` and `INV-EM-TOL-02` — the tolerance is relative and its margins are
/// invariant (P-35).
#[test]
fn inv_em_tol_01_the_tolerance_is_relative_with_invariant_margins() {
    let mut margins = Vec::new();
    for i_ph in [1e-3, 1e-1, 1.0, 10.4, 30.0] {
        let p = set(i_ph, 2.5e-10, 0.30, 800.0, 1.85);
        let tolerance = residual_tolerance(&p);
        let floor = 10.0 * f64::EPSILON * i_ph;
        margins.push(tolerance / floor);
        assert!(
            tolerance > floor,
            "the tolerance must stay above the round-off floor"
        );
    }
    // All equal: the margin does not depend on module size.
    for m in &margins {
        assert!(
            (m - margins[0]).abs() / margins[0] < 1e-12,
            "margins varied: {margins:?}"
        );
    }
    // And the margin is the one the analysis derived: about 450.
    assert!(
        margins[0] > 400.0 && margins[0] < 500.0,
        "margin = {}",
        margins[0]
    );
}

/// `INV-EM-TOL-02` — every returned point meets its tolerance.
#[test]
fn inv_em_tol_02_every_returned_point_meets_its_tolerance() {
    for (name, p) in reference_sets() {
        let tolerance = residual_tolerance(&p);
        sweep(&p, 25, |v| {
            let out = current_at_voltage(&p, v).expect("inside the quadrant");
            assert!(
                out.residual().abs() <= tolerance,
                "{name} at {} V: residual {:e} above {tolerance:e}",
                v.volts(),
                out.residual()
            );
        });
    }
}

